using System;
using System.IO;
using System.Security.Cryptography;
using System.Text;

namespace NX_Swite.Core.Configuracion
{
    /// <summary>
    /// Almacena y recupera el token de GitHub de forma segura usando DPAPI
    /// (<see cref="ProtectedData"/>), que cifra con la clave del perfil de Windows
    /// del usuario actual. El archivo cifrado nunca contiene el token en claro.
    ///
    /// Ruta: <c>%AppData%\NX-Swite\github_token.dat</c>
    ///
    /// Si el archivo no existe o est� da�ado, los m�todos devuelven <c>null</c>
    /// o <c>false</c> sin lanzar excepciones: el resto de la app debe tratar
    /// un token ausente como "modo an�nimo" sin interrumpir la instalaci�n.
    /// </summary>
    public static class TokenGitHub
    {
        private static readonly string _rutaToken = ConfiguracionLocal.RutaTokenGitHub;

        // ???????????????????????????????????????????????????????????????????
        //  Guardar
        // ???????????????????????????????????????????????????????????????????

        /// <summary>
        /// Cifra <paramref name="token"/> con DPAPI (scope usuario) y lo escribe
        /// en disco. Si <paramref name="token"/> es nulo o vac�o borra el archivo.
        /// </summary>
        public static void Guardar(string? token)
        {
            if (string.IsNullOrWhiteSpace(token))
            {
                Borrar();
                return;
            }

            try
            {
                Directory.CreateDirectory(ConfiguracionLocal.RutaAppData);
                byte[] datos    = Encoding.UTF8.GetBytes(token.Trim());
                byte[] cifrado  = ProtectedData.Protect(datos, null, DataProtectionScope.CurrentUser);
                File.WriteAllBytes(_rutaToken, cifrado);
            }
            catch (Exception ex)
            {
                Services.Logger.Warning($"TokenGitHub: no se pudo guardar el token: {ex.Message}");
            }
        }

        // ???????????????????????????????????????????????????????????????????
        //  Cargar
        // ???????????????????????????????????????????????????????????????????

        /// <summary>
        /// Lee y descifra el token. Devuelve <c>null</c> si no existe o est� da�ado.
        /// Nunca lanza excepciones.
        /// </summary>
        public static string? Cargar()
        {
            try
            {
                if (!File.Exists(_rutaToken)) return null;
                byte[] cifrado = File.ReadAllBytes(_rutaToken);
                byte[] datos   = ProtectedData.Unprotect(cifrado, null, DataProtectionScope.CurrentUser);
                return Encoding.UTF8.GetString(datos);
            }
            catch
            {
                return null;
            }
        }

        // ???????????????????????????????????????????????????????????????????
        //  Borrar
        // ???????????????????????????????????????????????????????????????????

        /// <summary>Elimina el archivo cifrado. No lanza excepciones.</summary>
        public static void Borrar()
        {
            try
            {
                if (File.Exists(_rutaToken))
                    File.Delete(_rutaToken);
            }
            catch { }
        }

        /// <summary>Indica si hay un token guardado (sin descifrar su contenido).</summary>
        public static bool HayToken => File.Exists(_rutaToken);
    }
}
